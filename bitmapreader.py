# Hàm xử lý để tạo ảnh
def hex_to_image(hex_str, width, height):
    # Làm sạch dữ liệu
    hex_str = hex_str.replace(" ", "").replace("\n", "")
    # Chuyển hex sang mảng nhị phân (1 bit = 1 pixel)
    # Vì mỗi byte là 8 bit, ta chuyển đổi sang mảng bool
    img_data = []
    for i in range(0, len(hex_str), 2):
        byte = int(hex_str[i:i+2], 16)
        for bit in range(7, -1, -1):
            img_data.append(255 if (byte >> bit) & 1 else 0)
    
    # Tạo ảnh từ mảng (giới hạn đúng kích thước 192x63)
    img = Image.new('1', (width, height))
    img.putdata(img_data[:width*height])
    return img

